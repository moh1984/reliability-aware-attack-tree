# 15_record_digests.ps1 — record the image digests actually used by this run.
#
# Floating tags (latest / stable / apache) move over time, so the tag alone does
# not identify the build a result was produced on. Run this AFTER `docker compose
# up -d` and after 02_zap_scan.ps1 has pulled the ZAP image. It writes
# results/IMAGE_DIGESTS.md, which pins the environment for anyone re-running the
# package later.

$ErrorActionPreference = "Stop"
$root = Split-Path -Parent $PSScriptRoot
$out  = Join-Path $root "results\IMAGE_DIGESTS.md"

# read the image refs from .env so this always matches docker-compose.yml
$envFile = Join-Path $root ".env"
$imgs = @{}
if (Test-Path $envFile) {
    Get-Content $envFile | Where-Object { $_ -match '^\s*[A-Z_]+\s*=' } | ForEach-Object {
        $k, $v = $_ -split '=', 2
        $imgs[$k.Trim()] = $v.Trim()
    }
} else {
    $imgs = @{
        DVWA_IMAGE      = "vulnerables/web-dvwa:latest"
        JUICESHOP_IMAGE = "bkimminich/juice-shop:latest"
        WAF_IMAGE       = "owasp/modsecurity-crs:apache"
        ZAP_IMAGE       = "ghcr.io/zaproxy/zaproxy:stable"
    }
}

$lines = @(
    "# Image digests for this run",
    "",
    "Generated by ``scripts/15_record_digests.ps1`` on $(Get-Date -Format 'yyyy-MM-dd HH:mm:ss K').",
    "",
    "To reproduce this exact environment, copy each digest into ``.env``, e.g.",
    "``DVWA_IMAGE=vulnerables/web-dvwa@sha256:<digest>``.",
    "",
    "| Variable | Tag used | RepoDigest |",
    "|---|---|---|"
)

foreach ($k in @("DVWA_IMAGE", "JUICESHOP_IMAGE", "WAF_IMAGE", "ZAP_IMAGE")) {
    $ref = $imgs[$k]
    if (-not $ref) { continue }
    $dig = (docker image inspect $ref --format '{{index .RepoDigests 0}}' 2>$null)
    if (-not $dig) { $dig = "(not present locally - pull it first)" }
    $lines += "| ``$k`` | ``$ref`` | ``$dig`` |"
}

$lines += @(
    "",
    "## Engine",
    "",
    '```'
)
$lines += (docker version --format 'Docker {{.Server.Version}} (API {{.Server.APIVersion}})' 2>$null)
$lines += (docker compose version 2>$null)
$lines += '```'

$lines | Set-Content -Encoding UTF8 $out
Write-Host "Saved $out" -ForegroundColor Green
Get-Content $out
